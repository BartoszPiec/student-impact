for (const category of JOB_CATEGORY_GROUPS) {
  CATEGORY_ALIASES.set(normalizeCategoryKey(category.label), category.label);
  CATEGORY_ALIASES.set(normalizeCategoryKey(category.slug), category.label);

  for (const subcategory of category.subcategories) {
    CATEGORY_ALIASES.set(normalizeCategoryKey(subcategory.label), category.label);
  }
}

export function resolveJobCategoryLabel(value: string | null | undefined): JobCategory | null {
  const key = normalizeCategoryKey(value);
  if (!key) return null;
  return CATEGORY_ALIASES.get(key) ?? null;
}

export function resolveJobCategorySlug(value: string | null | undefined): string | null {
  const label = resolveJobCategoryLabel(value);
  if (!label) return null;
  return JOB_CATEGORY_GROUPS.find((category) => category.label === label)?.slug ?? null;
}

export function getJobCategoryBySlug(slug: string | null | undefined) {
  return JOB_CATEGORY_GROUPS.find((category) => category.slug === slug) ?? null;
}

export function isAllowedJobCategory(value: string | null | undefined) {
  const label = resolveJobCategoryLabel(value);
  return Boolean(label && JOB_CATEGORY_LABEL_SET.has(label));
}

