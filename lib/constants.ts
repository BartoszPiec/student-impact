const JOB_CATEGORY_LABEL_SET = new Set<string>(JOB_CATEGORIES);

export function normalizeCategoryKey(value: string | null | undefined) {
  return String(value ?? "")
    .toLocaleLowerCase("pl-PL")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " i ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

